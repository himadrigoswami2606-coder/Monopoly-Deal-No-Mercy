  // ---------------------------------------------------------------------------
  // Background Lounge Music Generator (Authentic Casino Jazz Loop)
  // ---------------------------------------------------------------------------
  private isBgmPlaying = false;
  private bgmIntervalId: any = null;

  toggleBgm(forceState?: boolean): boolean {
    const nextState = forceState !== undefined ? forceState : !this.isBgmPlaying;
    if (nextState) {
      this.startBgm();
    } else {
      this.stopBgm();
    }
    return this.isBgmPlaying;
  }

  getBgmStatus(): boolean {
    return this.isBgmPlaying;
  }

  private startBgm(): void {
    const ctx = this.getContext();
    if (!ctx) return;
    if (this.isBgmPlaying) return;
    this.isBgmPlaying = true;

    // Smooth jazz progression: Cmaj7 - Am7 - Dm7 - G7 (pentatonic Monopoly lounge)
    const chords = [
      [261.63, 329.63, 392.0, 493.88], // Cmaj7
      [220.0, 261.63, 329.63, 392.0],  // Am7
      [293.66, 349.23, 440.0, 523.25], // Dm7
      [196.0, 246.94, 293.66, 349.23], // G7
    ];
    let chordIdx = 0;

    const playChordStep = () => {
      if (!this.isBgmPlaying) return;
      const currentCtx = this.getContext();
      if (!currentCtx) return;

      const chord = chords[chordIdx % chords.length];
      chordIdx++;

      chord.forEach((freq, noteIdx) => {
        const osc = currentCtx.createOscillator();
        const gain = currentCtx.createGain();
        osc.type = 'triangle';
        osc.frequency.setValueAtTime(freq, currentCtx.currentTime + noteIdx * 0.05);

        // Very soft background level (0.02)
        gain.gain.setValueAtTime(0.02, currentCtx.currentTime + noteIdx * 0.05);
        gain.gain.exponentialRampToValueAtTime(0.0005, currentCtx.currentTime + noteIdx * 0.05 + 1.8);

        osc.connect(gain);
        gain.connect(currentCtx.destination);
        osc.start(currentCtx.currentTime + noteIdx * 0.05);
        osc.stop(currentCtx.currentTime + noteIdx * 0.05 + 1.8);
      });
    };

    playChordStep();
    this.bgmIntervalId = setInterval(playChordStep, 2000);
  }

  private stopBgm(): void {
    this.isBgmPlaying = false;
    if (this.bgmIntervalId) {
      clearInterval(this.bgmIntervalId);
      this.bgmIntervalId = null;
    }
  }
